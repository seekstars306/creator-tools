var SUPPORTED_LANGS = ["en", "zh", "es", "pt", "ja"];
var LANG_KEY = "ct-lang";
function resolveLang(codes) {
  var list = codes || [];
  for (var i = 0; i < list.length; i++) {
    var c = String(list[i] || "").toLowerCase();
    if (c.indexOf("zh") === 0) return "zh";
    if (c.indexOf("es") === 0) return "es";
    if (c.indexOf("pt") === 0) return "pt";
    if (c.indexOf("ja") === 0) return "ja";
    if (c.indexOf("en") === 0) return "en";
  }
  return "en";
}
function getStoredLang() {
  try { return window.localStorage.getItem(LANG_KEY); } catch (e) { return null; }
}
function getInitialLang() {
  var stored = getStoredLang();
  if (stored && SUPPORTED_LANGS.indexOf(stored) >= 0) return stored;
  var nav = (typeof navigator !== "undefined") ? navigator : {};
  var codes = nav.languages && nav.languages.length ? nav.languages : (nav.language ? [nav.language] : []);
  return resolveLang(codes);
}
var currentLang = getInitialLang();
function t(key, params) {
  var dict = I18N[currentLang] || I18N.en;
  var s = dict[key];
  if (s === undefined && currentLang !== "en") {
    console.warn("[i18n] missing key for " + currentLang + ", falling back to en: " + key);
    s = I18N.en[key];
  }
  if (s === undefined) {
    console.warn("[i18n] missing key in en: " + key);
    return key;
  }
  if (params) {
    Object.keys(params).forEach(function (k) {
      s = s.split("{" + k + "}").join(String(params[k]));
    });
  }
  return s;
}
function applyI18n() {
  if (typeof document === "undefined") return;
  document.documentElement.lang = currentLang;
  var sel = document.getElementById("lang-select");
  if (sel) sel.value = currentLang;
  var els = document.querySelectorAll("[data-i18n]");
  for (var i = 0; i < els.length; i++) els[i].textContent = t(els[i].getAttribute("data-i18n"));
  var htmlEls = document.querySelectorAll("[data-i18n-html]");
  for (var j = 0; j < htmlEls.length; j++) htmlEls[j].innerHTML = t(htmlEls[j].getAttribute("data-i18n-html"));
  var phEls = document.querySelectorAll("[data-i18n-placeholder]");
  for (var k = 0; k < phEls.length; k++) phEls[k].placeholder = t(phEls[k].getAttribute("data-i18n-placeholder"));
  var ariaEls = document.querySelectorAll("[data-i18n-aria]");
  for (var a = 0; a < ariaEls.length; a++) ariaEls[a].setAttribute("aria-label", t(ariaEls[a].getAttribute("data-i18n-aria")));
  var page = document.body ? document.body.getAttribute("data-page") : null;
  if (page) {
    var mt = I18N[currentLang]["meta.title." + page] || I18N.en["meta.title." + page];
    if (mt) document.title = mt;
    var md = document.querySelector('meta[name="description"]');
    var mdText = I18N[currentLang]["meta.desc." + page] || I18N.en["meta.desc." + page];
    if (md && mdText) md.setAttribute("content", mdText);
  }
}
function setLang(lang) {
  if (SUPPORTED_LANGS.indexOf(lang) < 0) lang = "en";
  currentLang = lang;
  try { window.localStorage.setItem(LANG_KEY, lang); } catch (e) {}
  applyI18n();
}
if (typeof document !== "undefined") {
  applyI18n();
  var langSel = document.getElementById("lang-select");
  if (langSel) langSel.addEventListener("change", function (e) { setLang(e.target.value); });
}
window.__i18n = { t: t, setLang: setLang, getLang: function () { return currentLang; }, resolveLang: resolveLang, dict: I18N };
